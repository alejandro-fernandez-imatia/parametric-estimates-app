import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
import {companyKey} from './companies.js';
test('Interfaz multiempresa conserva datos y limpia deshacer',async()=>{
 const dom=new JSDOM(await readFile(new URL('index.html',import.meta.url),'utf8'),{url:'http://localhost:3000'});
 globalThis.document=dom.window.document;globalThis.localStorage=dom.window.localStorage;globalThis.FormData=dom.window.FormData;
 const $=s=>document.querySelector(s),change=(s,value)=>{const el=$(s);el.value=value;el.dispatchEvent(new dom.window.Event('change',{bubbles:true}));};
 const state=()=>JSON.parse(localStorage.getItem(companyKey));
 await import('./app.js');change('#customer','Cliente original');const original=$('#company-select').value;
 $('[data-view="companies"]').click();$('[data-demo-company="fontaneria"]').click();const plumbing=$('#company-select').value;
 assert.notEqual(plumbing,original);assert.match($('#content').textContent,/Reparar fuga/);assert.equal($('#undo').disabled,true);
 change('#customer','Cliente fontanero');assert.equal($('#undo').disabled,false);
 $('[data-view="companies"]').click();$('[data-demo-company="electricidad"]').click();assert.match($('#content').textContent,/Diagnóstico/);assert.equal($('#undo').disabled,true);
 change('#company-select',plumbing);assert.equal($('#customer').value,'Cliente fontanero');assert.equal($('#undo').disabled,true);
 change('#company-select',original);assert.equal($('#customer').value,'Cliente original');assert.equal(state().companies.length,3);
 $('[data-view="companies"]').click();$('#company-form [name="companyName"]').value='Nueva vacía';$('#company-form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
 assert.equal(state().companies.length,4);assert.equal(state().companies.at(-1).workspace.articles.length,0);
 $('[data-view="companies"]').click();
 globalThis.confirm=()=>false;$(`[data-delete-company="${plumbing}"]`).click();assert.equal(state().companies.length,4);
 globalThis.confirm=()=>true;$(`[data-delete-company="${plumbing}"]`).click();assert.equal(state().companies.length,3);assert.ok(!state().companies.some(c=>c.id===plumbing));
 assert.equal($('#undo').disabled,true);
 const active=state().active;$(`[data-delete-company="${active}"]`).click();assert.equal(state().active,original);assert.equal(state().companies.length,2);
 assert.equal(state().companies.find(c=>c.id===original).workspace.customer,'Cliente original');
 for(const company of [...state().companies])$(`[data-delete-company="${company.id}"]`).click();
 assert.equal(state().companies.length,1);assert.equal(state().companies[0].workspace.articles.length,0);assert.ok(![original,active].includes(state().active));
 dom.window.close();
});
